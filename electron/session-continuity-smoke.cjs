const fsp = require('node:fs/promises');
const path = require('node:path');
const { selectHarnessSession } = require('./harness-workspace-sync.cjs');
async function runContinuitySmoke({ window, rootDir, evaluate, waitFor, target, version, selected, origin, api }) {
  const checks = {}, wc = window.webContents;
  const mount = async () => {
    await waitFor('Boolean(document.querySelector("[data-composer-input][contenteditable=true]"))');
    for (const name of ['composer-text-bridge.js', 'document-intake.js', 'session-continuity.js']) await evaluate(await fsp.readFile(path.join(rootDir, 'assets', name), 'utf8'));
    await wc.insertCSS(await fsp.readFile(path.join(rootDir, 'assets', 'document-intake.css'), 'utf8'));
    await waitFor('window.__DSH_CONTINUITY__.ready()');
    await evaluate('Array.from(document.querySelectorAll("button")).find(b=>b.textContent.trim()==="稍后配置")?.click()');
  };
  const read = () => evaluate('window.__DSH_COMPOSER_TEXT__.read()');
  const flush = () => evaluate('window.__DSH_CONTINUITY__.flush()');
  const visit = async (id) => { await flush(); await selectHarnessSession(wc, id); await window.loadURL(origin); await mount(); };
  await mount();
  await evaluate('window.__DSH_COMPOSER_TEXT__.append(window.__DSH_COMPOSER_TEXT__.current(), "会话甲草稿，不要发送。")');
  await evaluate('document.querySelector(".dsh-document-actions button").click()');
  await waitFor('document.querySelectorAll(".dsh-document-chip").length === 1 && !window.__DSH_DOCUMENT_INTAKE__.isPending()');
  await flush(); const draftA = await read(); const domBefore = await evaluate('window.__DSH_COMPOSER_TEXT__.current().innerHTML');
  const stateA = await evaluate('desktopAPI.drafts.getState()');
  checks.persistedTextAndReference = stateA.text === draftA && stateA.items.length === 1;
  await window.loadURL(origin); await mount();
  await waitFor('window.__DSH_COMPOSER_TEXT__.read().includes("会话甲草稿")');
  const restoredA = await read(); const domRestored = await evaluate('window.__DSH_COMPOSER_TEXT__.current().innerHTML'); checks.reloadRestoresExactDraft = restoredA === draftA;
  await waitFor('document.querySelectorAll(".dsh-document-chip").length === 1');
  checks.reloadRestoresAttachmentChip = true;
  const other = await api(origin, 'session.create', { workspaceId: selected.workspaceId });
  await visit(other.sessionId);
  checks.newSessionEmpty = !(await read()).trim() && await evaluate('document.querySelectorAll(".dsh-document-chip").length === 0');
  await evaluate('window.__DSH_COMPOSER_TEXT__.append(window.__DSH_COMPOSER_TEXT__.current(), "会话乙的另一段草稿。")');
  await flush(); const draftB = await read();
  await visit(selected.sessionId);
  checks.sessionIsolationA = await read() === draftA;
  await visit(other.sessionId);
  checks.sessionIsolationB = await read() === draftB;
  checks.forgedTokenRejected = await evaluate('(async()=>{try{await desktopAPI.drafts.save({token:"forged",context:"x",text:"bad",revision:0});return false}catch{return true}})()');
  checks.staleRevisionRejected = await evaluate('(async()=>{const s=await desktopAPI.drafts.getState(); await desktopAPI.drafts.save({...s,text:s.text}); try{await desktopAPI.drafts.save({...s,text:"stale"});return false}catch{return true}})()');
  await window.loadURL(origin); await mount();
  await evaluate('window.__DSH_COMPOSER_TEXT__.remove(window.__DSH_COMPOSER_TEXT__.current(), window.__DSH_COMPOSER_TEXT__.read())');
  await flush(); await window.loadURL(origin); await mount();
  checks.clearedDraftStaysEmpty = !(await read()).trim();
  await visit(selected.sessionId);
  await fsp.writeFile(`${target}.png`, (await wc.capturePage()).toPNG());
  const newSession = await evaluate('(()=>{const button=Array.from(document.querySelectorAll("button")).find(b=>[b.getAttribute("aria-label"),b.title,b.textContent.trim()].some(t=>["新会话","New session","新建会话","New conversation"].includes(t))); if(!button)return false;button.click();return true})()');
  if (!newSession) throw new Error('New-session UI entry unavailable');
  await new Promise((resolve) => setTimeout(resolve, 700));
  await waitFor('window.__DSH_CONTINUITY__.ready()');
  await evaluate('window.__DSH_COMPOSER_TEXT__.append(window.__DSH_COMPOSER_TEXT__.current(), "全新会话的未发送草稿。")');
  await flush(); await window.loadURL(origin); await mount();
  checks.newUnsentDraftSurvives = (await read()).includes('全新会话的未发送草稿');
  return { ok: Object.values(checks).every(Boolean), version, evidence: 'real Harness Lexical editor, disk-backed reference, server-created sessions, reload and per-session persistence; no model request', checks, fixtureText: { before: draftA, restored: restoredA, domBefore, domRestored } };
}
module.exports = { runContinuitySmoke };
